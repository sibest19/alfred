test('fromWall: gaps move to the hour after, the repeated hour takes the second', () => {
  for (const [w, zone, at] of FROM_WALL) assert.equal(fromWall(...w, zone).toISOString(), at, `${w} in ${zone}`);
});

test('day, wall, wallMs, weekday', () => {
  for (const [at, zone, d, w, ms, wd] of INSTANTS) {
    const t = new Date(at);
    assert.deepEqual([day(t, zone), wall(t, zone), wallMs(t, zone), weekday(t, zone)], [d, w, ms, wd], `${at} in ${zone}`);
  }
});

test('when', () => {
  for (const [v, at, date] of WHEN) assert.deepEqual([when(v, 'x').at.toISOString(), when(v, 'x').date], [at, date], v);
});

test('dayAfter', () => {
  for (const [d, at] of DAY_AFTER) assert.equal(dayAfter(d).toISOString(), at, String(d));
});

test('when: a date that does not exist is a 400, not the day it rolls over to', () => {
  for (const v of ['2026-02-31', '2026-02-31 10:00', '2026-02-31T10:00+01:00', '2026-13-01', '2026-11-03 25:00', 'tomorrow']) {
    assert.throws(() => when(v, 'start'), { status: 400 }, v);
  }
});
